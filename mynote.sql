CREATE DATABASE IF NOT EXISTS mytest;

-- =============================================

-- 2. 切换到该数据库

-- =============================================

USE mytest;

-- =============================================

-- 3. 创建用户表（id、姓名、年龄、性别、邮箱）

-- 性别字段名已改为 sex

-- =============================================

CREATE TABLE user (

id INT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',

name VARCHAR(50) NOT NULL COMMENT '姓名',

age INT COMMENT '年龄',

sex VARCHAR(10) COMMENT '性别',

email VARCHAR(100) COMMENT '邮箱'

);

-- =============================================

-- 4. 查看表结构

-- =============================================

DESC user;

